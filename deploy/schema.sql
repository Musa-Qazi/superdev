-- Private PostgreSQL schema for Campus DevPulse.
-- The application connects using a server-side database credential.
CREATE SCHEMA IF NOT EXISTS devpulse;
REVOKE ALL ON SCHEMA devpulse FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS devpulse.modules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '',
  impact_score integer NOT NULL DEFAULT 3 CHECK (impact_score BETWEEN 1 AND 5),
  difficulty_score integer NOT NULL DEFAULT 3 CHECK (difficulty_score BETWEEN 1 AND 5),
  category text NOT NULL DEFAULT 'Other',
  active integer NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  display_order integer NOT NULL,
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS devpulse.developers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  initials text NOT NULL,
  role_label text NOT NULL DEFAULT '',
  active integer NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS devpulse.stages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id integer NOT NULL REFERENCES devpulse.modules(id) ON DELETE CASCADE,
  stage_type text NOT NULL CHECK (stage_type IN ('frontend', 'backend', 'integration', 'testing')),
  status text NOT NULL DEFAULT 'Not Started' CHECK (status IN ('Not Started', 'In Progress', 'Blocked', 'Completed')),
  progress integer NOT NULL DEFAULT 0 CHECK (progress BETWEEN 0 AND 100),
  assigned_developer_id integer REFERENCES devpulse.developers(id) ON DELETE SET NULL,
  notes text NOT NULL DEFAULT '',
  started_at text,
  completed_at text,
  updated_at text NOT NULL,
  UNIQUE (module_id, stage_type),
  CHECK (status != 'Completed' OR progress = 100),
  CHECK (status != 'Not Started' OR progress = 0)
);

CREATE TABLE IF NOT EXISTS devpulse.tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  module_id integer REFERENCES devpulse.modules(id) ON DELETE SET NULL,
  stage_type text CHECK (stage_type IS NULL OR stage_type IN ('frontend', 'backend', 'integration', 'testing')),
  assigned_developer_id integer REFERENCES devpulse.developers(id) ON DELETE SET NULL,
  status text NOT NULL DEFAULT 'To Do' CHECK (status IN ('To Do', 'In Progress', 'Blocked', 'Done')),
  priority text NOT NULL DEFAULT 'Medium' CHECK (priority IN ('Low', 'Medium', 'High')),
  due_date text,
  created_at text NOT NULL,
  updated_at text NOT NULL,
  completed_at text
);

CREATE TABLE IF NOT EXISTS devpulse.activity (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type text NOT NULL,
  entity_id integer NOT NULL,
  action text NOT NULL,
  summary text NOT NULL,
  timestamp text NOT NULL
);

CREATE TABLE IF NOT EXISTS devpulse.settings (
  key text PRIMARY KEY,
  value text NOT NULL,
  updated_at text NOT NULL
);

CREATE INDEX IF NOT EXISTS stages_assigned_developer_idx ON devpulse.stages (assigned_developer_id);
CREATE INDEX IF NOT EXISTS tasks_assigned_developer_idx ON devpulse.tasks (assigned_developer_id);
CREATE INDEX IF NOT EXISTS tasks_module_idx ON devpulse.tasks (module_id);
REVOKE ALL ON ALL TABLES IN SCHEMA devpulse FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA devpulse FROM PUBLIC, anon, authenticated;
